-- Disposable native PostgreSQL ONLY. Minimal managed schemas, not provider emulation.
create role anon;
create role authenticated;
create role service_role bypassrls;
create schema auth;
create schema storage;
create schema realtime;
create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,created_at timestamptz default now(),last_sign_in_at timestamptz,raw_user_meta_data jsonb,raw_app_meta_data jsonb);
create table auth.identities(id uuid primary key,user_id uuid,provider_id text,provider text,identity_data jsonb,created_at timestamptz default now());
create function auth.uid() returns uuid language sql stable as $$
 select nullif(coalesce(current_setting('request.jwt.claim.sub',true),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub'),'')::uuid
$$;
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb,user_metadata jsonb);
alter table storage.objects enable row level security;
create table realtime.messages(id bigint generated by default as identity primary key,topic text,extension text,private boolean,payload jsonb,event text);
alter table realtime.messages enable row level security;
create function realtime.topic() returns text language sql stable as $$ select nullif(current_setting('realtime.topic',true),'') $$;
-- Local recording sink proves transactional invalidation calls, NOT WebSockets.
create function realtime.send(payload jsonb,event text,topic text,private boolean default true) returns void language sql as $$
 insert into realtime.messages(topic,extension,private,payload,event) values($3,'broadcast',$4,$1,$2)
$$;
grant usage on schema auth,storage,realtime,public to anon,authenticated,service_role;
grant select,insert,update,delete on storage.objects to anon,authenticated,service_role;
grant select,insert on realtime.messages to anon,authenticated;
grant usage on sequence realtime.messages_id_seq to anon,authenticated;
